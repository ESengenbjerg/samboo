create table public.groups (
  id          bigint generated by default as identity,
  created_at  timestamptz not null default now(),
  constraint groups_pkey primary key (id)
);

create table public.profiles (
  id                       uuid not null,
  name                     text not null,
  group_id                 bigint,
  is_active                boolean not null default true,
  created_at               timestamptz not null default now(),
  onboarding_completed_at  timestamptz,
  constraint profiles_pkey primary key (id),
  constraint profiles_id_fkey       foreign key (id)       references auth.users (id) on delete cascade,
  constraint profiles_group_id_fkey foreign key (group_id) references public.groups (id) on delete set null
);

create table public.invites (
  id            bigint generated by default as identity,
  created_at    timestamptz not null default now(),
  from_user_id  uuid not null,
  to_email      text not null,
  status        text not null default 'pending',
  constraint invites_pkey primary key (id),
  constraint invites_status_check check (status = any (array['pending', 'accepted', 'declined'])),
  constraint invites_from_user_id_fkey foreign key (from_user_id) references public.profiles (id) on delete cascade
);

-- Scraped listings. Shared data, not tied to any user.
create table public.listings (
  id             bigint generated by default as identity,
  created_at     timestamptz not null default now(),
  agency         text not null,
  external_id    bigint not null,
  url            text not null,
  ld_json        jsonb not null,
  last_seen_at   timestamptz not null default now(),
  removed_at     timestamptz,
  property_type  text,
  municipality   text,
  area           text,
  price          bigint,
  rooms          numeric,
  latitude       double precision,
  longitude      double precision,
  constraint listings_pkey primary key (id),
  constraint listings_agency_external_id_key unique (agency, external_id),
  constraint listings_property_type_check check (
    property_type = any (array['villa', 'radhus', 'lagenhet', 'fritidshus', 'tomt', 'other'])
  )
);

-- At most one search profile per user (unique user_id).
create table public.search_params (
  id              bigint generated by default as identity,
  created_at      timestamptz not null default now(),
  user_id         uuid not null,
  property_types  text[] not null default '{}'::text[],
  municipalities  text[] not null default '{}'::text[],
  areas           text[] not null default '{}'::text[],
  min_price       bigint,
  max_price       bigint,
  min_rooms       numeric,
  max_rooms       numeric,
  constraint "SearchParams_pkey" primary key (id),
  constraint "SearchParams_user_id_key" unique (user_id),
  constraint "SearchParams_user_id_fkey" foreign key (user_id) references public.profiles (id) on delete cascade,
  constraint search_params_price_check check (min_price is null or max_price is null or min_price <= max_price),
  constraint search_params_rooms_check check (min_rooms is null or max_rooms is null or min_rooms <= max_rooms),
  constraint search_params_property_types_check check (
    property_types <@ array['villa', 'radhus', 'lagenhet', 'fritidshus', 'tomt', 'other']
  )
);

-- Match between user and listing. Filled by match_user_listings() and like_listing().
create table public.user_listings (
  id          bigint generated by default as identity,
  created_at  timestamptz not null default now(),
  user_id     uuid not null,
  listing_id  bigint not null,
  is_new      boolean not null default true,
  liked       boolean not null default false,
  constraint user_listings_pkey primary key (id),
  constraint user_listings_unique unique (user_id, listing_id),
  constraint user_listings_user_id_fkey    foreign key (user_id)    references public.profiles (id) on delete cascade,
  constraint user_listings_listing_id_fkey foreign key (listing_id) references public.listings (id) on delete cascade
);

create table public.user_tags (
  id          bigint generated by default as identity,
  created_at  timestamptz not null default now(),
  user_id     uuid not null,
  tag_name    text not null,
  constraint user_tags_pkey primary key (id),
  constraint user_tags_unique unique (user_id, tag_name),
  constraint user_tags_user_id_fkey foreign key (user_id) references public.profiles (id) on delete cascade
);

create table public.listing_tags (
  id               bigint generated by default as identity,
  created_at       timestamptz not null default now(),
  user_tag_id      bigint not null,
  user_listing_id  bigint not null,
  constraint listing_tags_pkey primary key (id),
  constraint listing_tags_unique unique (user_tag_id, user_listing_id),
  constraint listing_tags_user_tag_id_fkey     foreign key (user_tag_id)     references public.user_tags (id) on delete cascade,
  constraint listing_tags_user_listing_id_fkey foreign key (user_listing_id) references public.user_listings (id) on delete cascade
);

