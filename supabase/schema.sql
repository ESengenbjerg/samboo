-- Creates the profile row when an auth user is created (see trigger below).
CREATE OR REPLACE FUNCTION public.handle_new_user()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  insert into public.profiles (id, name, is_active)
  values (
    new.id,
    left(
      coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), split_part(new.email, '@', 1)),
      100
    ),
    true
  )
  on conflict (id) do nothing;
  return new;
end;
$function$;

-- Used by nearly all RLS policies.
CREATE OR REPLACE FUNCTION public.is_active_user()
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select coalesce(
    (
      select p.is_active and u.email_confirmed_at is not null
      from public.profiles p
      join auth.users u on u.id = p.id
      where p.id = (select auth.uid())
    ),
    false
  );
$function$;

CREATE OR REPLACE FUNCTION public.my_group_id()
 RETURNS bigint
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select group_id from public.profiles where id = auth.uid()
$function$;

CREATE OR REPLACE FUNCTION public.in_my_group(target uuid)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select target = auth.uid()
      or exists (
        select 1 from public.profiles p
        where p.id = target
          and p.group_id is not null
          and p.group_id = public.my_group_id()
      )
$function$;

CREATE OR REPLACE FUNCTION public.shares_group_with(target uuid)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select
    target = (select auth.uid())
    or exists (
      select 1
      from public.profiles me
      join public.profiles other on other.group_id = me.group_id
      where me.id = (select auth.uid())
        and other.id = target
        and me.group_id is not null
    );
$function$;

-- A group has at most 10 members (MAX_GROUP_MEMBERS). The group row is locked while counting, so two simultaneous accepts cannot both take the last place.
-- Both profile rows are locked first (in id order) and the invite is read again after the lock, so a double tap or two crossing accepts cannot create two groups. A pending invite in the opposite direction between the same two users is cancelled.
CREATE OR REPLACE FUNCTION public.accept_invite(invite_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  me uuid := auth.uid();
  my_email text := lower(auth.jwt() ->> 'email');
  inv public.invites;
  v_from uuid;
  v_from_email text;
  my_g bigint;
  g bigint;
begin
  if not public.is_active_user() then
    raise exception 'Ditt konto är inte aktivt';
  end if;

  select from_user_id into v_from from public.invites
  where id = invite_id and status = 'pending' and lower(to_email) = my_email;
  if not found then
    raise exception 'Inbjudan finns inte eller är inte din';
  end if;

  -- Lock both profile rows in a fixed order (id), so crossing accepts cannot lock each other up.
  perform 1 from public.profiles where id in (me, v_from) order by id for update;

  -- After the lock: read again and check again. A double tap or a crossing accept no longer finds the invite.
  select * into inv from public.invites
  where id = invite_id and status = 'pending' and lower(to_email) = my_email
  for update;
  if not found then
    raise exception 'Inbjudan finns inte eller är inte din';
  end if;

  select group_id into my_g from public.profiles where id = me;
  if my_g is not null then
    raise exception 'Du är redan med i en grupp. Lämna den först.';
  end if;

  select group_id into g from public.profiles where id = v_from;
  if g is null then
    insert into public.groups default values returning id into g;
    update public.profiles set group_id = g where id = v_from;
  else
    perform 1 from public.groups where id = g for update;
    if (select count(*) from public.profiles where group_id = g) >= 10 then
      raise exception 'Gruppen är full (max 10 medlemmar)';
    end if;
  end if;

  update public.profiles set group_id = g where id = me;
  update public.invites set status = 'accepted', responded_at = now() where id = invite_id;

  -- A pending invite from me to the sender is now pointless: close it.
  select email into v_from_email from auth.users where id = v_from;
  update public.invites
  set status = 'cancelled', responded_at = now()
  where from_user_id = me
    and lower(to_email) = lower(v_from_email)
    and status = 'pending';
end;
$function$;

CREATE OR REPLACE FUNCTION public.decline_invite(invite_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  if not public.is_active_user() then
    raise exception 'Ditt konto är inte aktivt';
  end if;

  update public.invites
  set status = 'declined', responded_at = now()
  where id = invite_id
    and status = 'pending'
    and lower(to_email) = lower(auth.jwt() ->> 'email');

  if not found then
    raise exception 'Inbjudan finns inte eller är inte din';
  end if;
end;
$function$;

-- The sender withdraws a pending invite (e.g. wrong e-mail address). The row is kept with status 'cancelled' so it still counts towards the 20 per pair limit.
CREATE OR REPLACE FUNCTION public.cancel_invite(invite_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  if not public.is_active_user() then
    raise exception 'Ditt konto är inte aktivt';
  end if;

  update public.invites
  set status = 'cancelled', responded_at = now()
  where id = invite_id
    and status = 'pending'
    and from_user_id = auth.uid();

  if not found then
    raise exception 'Inbjudan finns inte eller är inte din';
  end if;
end;
$function$;

-- Pending invites addressed to me, with the sender's name and e-mail. Needed because the recipient cannot read the sender's profile (not in the same group) or auth.users.
CREATE OR REPLACE FUNCTION public.my_pending_invites()
 RETURNS TABLE (id bigint, created_at timestamptz, from_user_id uuid, from_name text, from_email text)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select i.id, i.created_at, i.from_user_id, p.name, u.email::text
  from public.invites i
  join public.profiles p on p.id = i.from_user_id
  join auth.users u on u.id = i.from_user_id
  where public.is_active_user()
    and p.is_active
    and i.status = 'pending'
    and lower(i.to_email) = lower(auth.jwt() ->> 'email')
  order by i.created_at desc;
$function$;

-- Shared group rule: dissolves the group if at most 1 member is left. Used by leave_group(), remove_group_member() and handle_deleted_profile(). Callers lock the group row first.
CREATE OR REPLACE FUNCTION public.dissolve_group_if_alone(g bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  kvar int;
begin
  select count(*) into kvar from public.profiles where group_id = g;
  if kvar <= 1 then
    update public.profiles set group_id = null where group_id = g;
    delete from public.groups where id = g;
  end if;
end;
$function$;

-- The group row is locked, then my membership is checked again, so simultaneous leaves/removals are handled one at a time.
CREATE OR REPLACE FUNCTION public.leave_group()
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  g bigint := public.my_group_id();
  cur bigint;
begin
  if g is null then
    raise exception 'Du är inte med i någon grupp';
  end if;

  perform 1 from public.groups where id = g for update;

  select group_id into cur from public.profiles where id = auth.uid();
  if cur is distinct from g then
    raise exception 'Du är inte med i någon grupp';
  end if;

  update public.profiles set group_id = null where id = auth.uid();
  perform public.dissolve_group_if_alone(g);
end;
$function$;

-- Any member can remove any other member of the same group (no roles). Same cascade as leave_group().
CREATE OR REPLACE FUNCTION public.remove_group_member(target uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  g bigint;
  cur bigint;
  target_group bigint;
begin
  if not public.is_active_user() then
    raise exception 'Ditt konto är inte aktivt';
  end if;

  if target is null or target = auth.uid() then
    raise exception 'Använd "Lämna grupp" för att lämna din egen grupp';
  end if;

  g := public.my_group_id();
  if g is null then
    raise exception 'Du är inte med i någon grupp';
  end if;

  perform 1 from public.groups where id = g for update;

  -- After the lock: check again, someone may have changed the group in the meantime.
  select group_id into cur from public.profiles where id = auth.uid();
  if cur is distinct from g then
    raise exception 'Du är inte med i någon grupp';
  end if;

  select group_id into target_group from public.profiles where id = target;
  if target_group is distinct from g then
    raise exception 'Personen är inte med i din grupp';
  end if;

  update public.profiles set group_id = null where id = target;
  perform public.dissolve_group_if_alone(g);
end;
$function$;

CREATE OR REPLACE FUNCTION public.like_listing(p_listing_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  if not public.is_active_user() then
    raise exception 'Ditt konto är inte aktivt';
  end if;

  -- Only listings that are already visible to me: matched to me or to someone in my group
  if not exists (
    select 1 from public.user_listings ul
    where ul.listing_id = p_listing_id
      and public.shares_group_with(ul.user_id)
  ) then
    raise exception 'Annonsen finns inte eller är inte tillgänglig för dig';
  end if;

  insert into public.user_listings (user_id, listing_id, liked, is_new)
  values (auth.uid(), p_listing_id, true, false)
  on conflict (user_id, listing_id) do update set liked = true;
end;
$function$;

-- The shared list ("Gemensam-listan"): listings that EVERY member of the group has liked.
CREATE OR REPLACE FUNCTION public.shared_likes()
 RETURNS SETOF listings
 LANGUAGE sql
 STABLE
AS $function$
  select l.* from public.listings l
  where l.id in (
    select ul.listing_id
    from public.user_listings ul
    join public.profiles p on p.id = ul.user_id
    where p.group_id = public.my_group_id() and ul.liked
    group by ul.listing_id
    having count(*) = (select count(*) from public.profiles
                       where group_id = public.my_group_id())
  )
$function$;

-- Run by the trigger on search_params and by the scraper (service_role).
CREATE OR REPLACE FUNCTION public.match_user_listings(p_user_id uuid DEFAULT NULL::uuid)
 RETURNS integer
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare
  inserted integer;
begin
  with matches as (
    -- Every (user, listing) pair that currently matches a search
    select sp.user_id, l.id as listing_id
    from public.search_params sp
    join public.listings l on (
          -- Type: empty list = all types. A listing without a type never matches a chosen type
          (cardinality(sp.property_types) = 0 or l.property_type = any (sp.property_types))

          -- Location: municipality OR area. Both lists empty = no match (a search without a place gets no listings)
      and (
            l.municipality = any (sp.municipalities)
            or l.area = any (sp.areas)
          )

          -- Price: unknown price passes
      and (sp.min_price is null or l.price is null or l.price >= sp.min_price)
      and (sp.max_price is null or l.price is null or l.price <= sp.max_price)

          -- Rooms: unknown rooms passes
      and (sp.min_rooms is null or l.rooms is null or l.rooms >= sp.min_rooms)
      and (sp.max_rooms is null or l.rooms is null or l.rooms <= sp.max_rooms)

          -- Monthly fee: unknown fee passes (houses and plots have none)
      and (sp.max_monthly_fee is null or l.monthly_fee is null or l.monthly_fee <= sp.max_monthly_fee)

          -- Living area: unknown area passes
      and (sp.min_living_area is null or l.living_area is null or l.living_area >= sp.min_living_area)

          -- New builds: shown unless the user has turned them off (null = shown)
      and (sp.include_new_construction is not false or not l.is_new_construction)
    )
    where (p_user_id is null or sp.user_id = p_user_id)
      and l.removed_at is null
  ),
  stale as (
    -- Rows that no longer match. Liked and tagged listings are kept.
    -- Removed listings are kept too: they show as "Hittas inte" until purged after 14 days
    delete from public.user_listings ul
    where (p_user_id is null or ul.user_id = p_user_id)
      and exists (select 1 from public.search_params sp where sp.user_id = ul.user_id)
      and not ul.liked
      and not exists (select 1 from public.listing_tags lt where lt.user_listing_id = ul.id)
      and not exists (
        select 1 from public.listings l
        where l.id = ul.listing_id and l.removed_at is not null
      )
      and not exists (
        select 1 from matches m
        where m.user_id = ul.user_id and m.listing_id = ul.listing_id
      )
    returning ul.id
  )
  insert into public.user_listings (user_id, listing_id, is_new, liked)
  select m.user_id, m.listing_id, true, false
  from matches m
  on conflict (user_id, listing_id) do nothing;

  get diagnostics inserted = row_count;
  return inserted;
end;
$function$;

-- At most 20 invites in total (any status) from one sender to one recipient. Declined invites are kept so they count.
CREATE OR REPLACE FUNCTION public.limit_invites_per_pair()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  if (
    select count(*) from public.invites
    where from_user_id = new.from_user_id
      and lower(to_email) = lower(new.to_email)
  ) >= 20 then
    raise exception 'Du har skickat för många inbjudningar till den här personen';
  end if;
  return new;
end;
$function$;

