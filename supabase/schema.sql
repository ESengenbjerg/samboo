create table public.groups (
  id          bigint generated by default as identity,
  created_at  timestamptz not null default now(),
  constraint groups_pkey primary key (id)
);

create table public.profiles (
  id                       uuid not null,
  name                     text not null,
  group_id                 bigint,
  is_active                boolean not null default true,
  created_at               timestamptz not null default now(),
  onboarding_completed_at  timestamptz,
  -- Profile image, stored as a URL (https only)
  avatar_url               text,
  constraint profiles_pkey primary key (id),
  constraint profiles_id_fkey       foreign key (id)       references auth.users (id) on delete cascade,
  constraint profiles_group_id_fkey foreign key (group_id) references public.groups (id) on delete set null,
  constraint profiles_name_length check (char_length(name) between 1 and 100),
  constraint profiles_avatar_url_check check (avatar_url is null or (char_length(avatar_url) <= 2048 and avatar_url ~ '^https://'))
);

create table public.invites (
  id            bigint generated by default as identity,
  created_at    timestamptz not null default now(),
  from_user_id  uuid not null,
  to_email      text not null,
  status        text not null default 'pending',
  -- When the invite left 'pending' (accepted, declined or cancelled). Used by purge_old_invites()
  responded_at  timestamptz,
  constraint invites_pkey primary key (id),
  -- 'cancelled' = withdrawn by the sender. Kept (not deleted) so it still counts towards the 20 per pair limit. Hidden from the recipient by invites_select
  constraint invites_status_check check (status = any (array['pending', 'accepted', 'declined', 'cancelled'])),
  constraint invites_from_user_id_fkey foreign key (from_user_id) references public.profiles (id) on delete cascade,
  -- 254 = longest possible e-mail address (RFC 5321)
  constraint invites_email_length check (char_length(to_email) <= 254)
);

-- Scraped listings. Shared data, not tied to any user.
create table public.listings (
  id             bigint generated by default as identity,
  created_at     timestamptz not null default now(),
  agency         text not null,
  external_id    bigint not null,
  url            text not null,
  ld_json        jsonb not null,
  last_seen_at   timestamptz not null default now(),
  removed_at     timestamptz,
  property_type  text,
  municipality   text,
  area           text,
  price          bigint,
  rooms          numeric,
  latitude       double precision,
  longitude      double precision,
  monthly_fee    bigint,
  living_area    numeric,
  is_new_construction boolean not null default false,
  constraint listings_pkey primary key (id),
  constraint listings_agency_external_id_key unique (agency, external_id),
  constraint listings_property_type_check check (
    property_type = any (array['villa', 'radhus', 'lagenhet', 'fritidshus', 'tomt', 'other'])
  )
);

-- At most one search profile per user (unique user_id).
create table public.search_params (
  id              bigint generated by default as identity,
  created_at      timestamptz not null default now(),
  user_id         uuid not null,
  property_types  text[] not null default '{}'::text[],
  municipalities  text[] not null default '{}'::text[],
  areas           text[] not null default '{}'::text[],
  min_price       bigint,
  max_price       bigint,
  min_rooms       numeric,
  max_rooms       numeric,
  max_monthly_fee bigint,
  min_living_area numeric,
  -- null counts as true: new builds are shown unless the user turns them off
  include_new_construction boolean default true,
  constraint "SearchParams_pkey" primary key (id),
  constraint "SearchParams_user_id_key" unique (user_id),
  constraint "SearchParams_user_id_fkey" foreign key (user_id) references public.profiles (id) on delete cascade,
  constraint search_params_price_check check (min_price is null or max_price is null or min_price <= max_price),
  constraint search_params_rooms_check check (min_rooms is null or max_rooms is null or min_rooms <= max_rooms),
  constraint search_params_monthly_fee_check check (max_monthly_fee is null or max_monthly_fee >= 0),
  constraint search_params_living_area_check check (min_living_area is null or min_living_area >= 0),
  constraint search_params_property_types_check check (
    property_types <@ array['villa', 'radhus', 'lagenhet', 'fritidshus', 'tomt', 'other']
  ),
  -- Caps the size of one search so nobody can make the scraper cover the whole country
  constraint search_params_place_limit check (cardinality(municipalities) <= 10 and cardinality(areas) <= 20)
);

