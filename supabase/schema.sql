  for insert to authenticated
  with check (
    is_active_user()
    and exists (
      select 1 from user_listings ul
      where ul.id = listing_tags.user_listing_id and ul.user_id = (select auth.uid())
    )
    and exists (
      select 1 from user_tags ut
      where ut.id = listing_tags.user_tag_id and ut.user_id = (select auth.uid())
    )
  );

create policy listing_tags_delete on public.listing_tags
  for delete to authenticated
  using (is_active_user() and exists (
    select 1 from user_listings ul
    where ul.id = listing_tags.user_listing_id and ul.user_id = (select auth.uid())
  ));

-- listings (those matched to me or to someone in my group)
create policy listings_select_matched on public.listings
  for select to authenticated
  using (is_active_user() and exists (
    select 1 from user_listings ul
    where ul.listing_id = listings.id and shares_group_with(ul.user_id)
  ));

