-- Creates the profile row when an auth user is created (see trigger below).
CREATE OR REPLACE FUNCTION public.handle_new_user()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  insert into public.profiles (id, name, is_active)
  values (
    new.id,
    left(
      coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), split_part(new.email, '@', 1)),
      100
    ),
    true
  )
  on conflict (id) do nothing;
  return new;
end;
$function$;

-- Used by nearly all RLS policies.
CREATE OR REPLACE FUNCTION public.is_active_user()
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select coalesce(
    (
      select p.is_active and u.email_confirmed_at is not null
      from public.profiles p
      join auth.users u on u.id = p.id
      where p.id = (select auth.uid())
    ),
    false
  );
$function$;

CREATE OR REPLACE FUNCTION public.my_group_id()
 RETURNS bigint
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select group_id from public.profiles where id = auth.uid()
$function$;

CREATE OR REPLACE FUNCTION public.in_my_group(target uuid)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select target = auth.uid()
      or exists (
        select 1 from public.profiles p
        where p.id = target
          and p.group_id is not null
          and p.group_id = public.my_group_id()
      )
$function$;

CREATE OR REPLACE FUNCTION public.shares_group_with(target uuid)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select
    target = (select auth.uid())
    or exists (
      select 1
      from public.profiles me
      join public.profiles other on other.group_id = me.group_id
      where me.id = (select auth.uid())
        and other.id = target
        and me.group_id is not null
    );
$function$;

CREATE OR REPLACE FUNCTION public.accept_invite(invite_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  inv public.invites;
  g bigint;
begin
  select * into inv from public.invites
  where id = invite_id
    and status = 'pending'
    and lower(to_email) = lower(auth.jwt() ->> 'email');

  if not found then
    raise exception 'Inbjudan finns inte eller är inte din';
  end if;

  if public.my_group_id() is not null then
    raise exception 'Du är redan med i en grupp. Lämna den först.';
  end if;

  select group_id into g from public.profiles where id = inv.from_user_id;
  if g is null then
    insert into public.groups default values returning id into g;
    update public.profiles set group_id = g where id = inv.from_user_id;
  end if;

  update public.profiles set group_id = g where id = auth.uid();
  update public.invites set status = 'accepted' where id = invite_id;
end;
$function$;

CREATE OR REPLACE FUNCTION public.leave_group()
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  g bigint := public.my_group_id();
  kvar int;
begin
  if g is null then
    raise exception 'Du är inte med i någon grupp';
  end if;

  update public.profiles set group_id = null where id = auth.uid();

  select count(*) into kvar from public.profiles where group_id = g;
  if kvar <= 1 then
    update public.profiles set group_id = null where group_id = g;
    delete from public.groups where id = g;
  end if;
end;
$function$;

CREATE OR REPLACE FUNCTION public.like_listing(p_listing_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  insert into public.user_listings (user_id, listing_id, liked, is_new)
  values (auth.uid(), p_listing_id, true, false)
  on conflict (user_id, listing_id) do update set liked = true;
end;
$function$;

-- The shared list ("Gemensam-listan"): listings that EVERY member of the group has liked.
CREATE OR REPLACE FUNCTION public.shared_likes()
 RETURNS SETOF listings
 LANGUAGE sql
 STABLE
AS $function$
  select l.* from public.listings l
  where l.id in (
    select ul.listing_id
    from public.user_listings ul
    join public.profiles p on p.id = ul.user_id
    where p.group_id = public.my_group_id() and ul.liked
    group by ul.listing_id
    having count(*) = (select count(*) from public.profiles
                       where group_id = public.my_group_id())
  )
$function$;

-- Run by the trigger on search_params and by the scraper (service_role).
CREATE OR REPLACE FUNCTION public.match_user_listings(p_user_id uuid DEFAULT NULL::uuid)
 RETURNS integer
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare
  inserted integer;
begin
  with matches as (
    -- Every (user, listing) pair that currently matches a search
    select sp.user_id, l.id as listing_id
    from public.search_params sp
    join public.listings l on (
          -- Type: empty list = all types. A listing without a type never matches a chosen type
          (cardinality(sp.property_types) = 0 or l.property_type = any (sp.property_types))

          -- Location: municipality OR area. Both lists empty = anywhere
      and (
            (cardinality(sp.municipalities) = 0 and cardinality(sp.areas) = 0)
            or l.municipality = any (sp.municipalities)
            or l.area = any (sp.areas)
          )

          -- Price: unknown price passes
      and (sp.min_price is null or l.price is null or l.price >= sp.min_price)
      and (sp.max_price is null or l.price is null or l.price <= sp.max_price)

          -- Rooms: unknown rooms passes
      and (sp.min_rooms is null or l.rooms is null or l.rooms >= sp.min_rooms)
      and (sp.max_rooms is null or l.rooms is null or l.rooms <= sp.max_rooms)
    )
    where (p_user_id is null or sp.user_id = p_user_id)
      and l.removed_at is null
  ),
  stale as (
    -- Rows that no longer match. Liked and tagged listings are kept.
    -- Removed listings are kept too: they show as "Hittas inte" until purged after 14 days
    delete from public.user_listings ul
    where (p_user_id is null or ul.user_id = p_user_id)
      and exists (select 1 from public.search_params sp where sp.user_id = ul.user_id)
      and not ul.liked
      and not exists (select 1 from public.listing_tags lt where lt.user_listing_id = ul.id)
      and not exists (
        select 1 from public.listings l
        where l.id = ul.listing_id and l.removed_at is not null
      )
      and not exists (
        select 1 from matches m
        where m.user_id = ul.user_id and m.listing_id = ul.listing_id
      )
    returning ul.id
  )
  insert into public.user_listings (user_id, listing_id, is_new, liked)
  select m.user_id, m.listing_id, true, false
  from matches m
  on conflict (user_id, listing_id) do nothing;

  get diagnostics inserted = row_count;
  return inserted;
end;
$function$;

CREATE OR REPLACE FUNCTION public.search_params_match_trigger()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  perform public.match_user_listings(new.user_id);
  return new;
end;
$function$;

-- Account deletion, part 1: dissolves the group if at most 1 member remains after a profile has been deleted (same rule as leave_group()).
CREATE OR REPLACE FUNCTION public.handle_deleted_profile()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  kvar int;
begin
  if old.group_id is null then
    return old;
  end if;

  select count(*) into kvar from public.profiles where group_id = old.group_id;
  if kvar <= 1 then
    update public.profiles set group_id = null where group_id = old.group_id;
    delete from public.groups where id = old.group_id;
  end if;
  return old;
end;
$function$;

-- Account deletion, part 2: called by the app. Deletes the signed-in user from auth.users; everything else follows via ON DELETE CASCADE and the trigger above.
CREATE OR REPLACE FUNCTION public.delete_my_account()
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  if auth.uid() is null then
    raise exception 'Not signed in';
  end if;
  delete from auth.users where id = auth.uid();
end;
$function$;

-- Deletes listings that have been removed for more than 14 days.
CREATE OR REPLACE FUNCTION public.purge_removed_listings()
 RETURNS integer
 LANGUAGE sql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  with deleted as (
    delete from public.listings
    where removed_at < now() - interval '14 days'
    returning 1
  )
  select count(*)::int from deleted;
$function$;

-- Automatically enables RLS on new tables in public.
CREATE OR REPLACE FUNCTION public.rls_auto_enable()
 RETURNS event_trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog'
AS $function$
DECLARE
  cmd record;
  tbl name;
BEGIN
  FOR cmd IN
    SELECT *
    FROM pg_event_trigger_ddl_commands()
    WHERE command_tag IN ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      AND object_type IN ('table','partitioned table')
  LOOP
     IF cmd.schema_name IS NOT NULL AND cmd.schema_name IN ('public') AND cmd.schema_name NOT IN ('pg_catalog','information_schema') AND cmd.schema_name NOT LIKE 'pg_toast%' AND cmd.schema_name NOT LIKE 'pg_temp%' THEN
      BEGIN
        SELECT c.relname INTO tbl FROM pg_catalog.pg_class c WHERE c.oid = cmd.objid;
        EXECUTE format('alter table if exists %I.%I enable row level security', cmd.schema_name, tbl);
        RAISE LOG 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      EXCEPTION
        WHEN OTHERS THEN
          RAISE LOG 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      END;
     ELSE
        RAISE LOG 'rls_auto_enable: skip % (either system schema or not in enforced list: %.)', cmd.object_identity, cmd.schema_name;
     END IF;
  END LOOP;
END;
$function$;


