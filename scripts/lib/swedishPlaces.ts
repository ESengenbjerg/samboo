// "Västra Götaland" -> "vastra-gotaland", "Upplands Väsby" -> "upplands-vasby"
export function slugify(name: string): string {
  return name
    .trim()
    .toLowerCase()
    .replace(/[åä]/g, "a")
    .replace(/ö/g, "o")
    .replace(/\s+/g, "-")
    .replace(/[^a-z0-9-]/g, "");
}

// Municipality -> its county. Looked up by exact lowercase name first, because
// "Håbo" (Uppsala) and "Habo" (Jönköping) get the same slug, then by slug
const COUNTY_BY_NAME = new Map<string, string>();
const COUNTY_BY_SLUG = new Map<string, string>();
for (const [county, municipalities] of Object.entries(COUNTIES)) {
  for (const m of municipalities) {
    COUNTY_BY_NAME.set(m.toLowerCase(), county);
    COUNTY_BY_SLUG.set(slugify(m), county);
  }
}

// "Partille" -> "Västra Götaland". Null for an unknown municipality
export function countyOf(municipality: string): string | null {
  return (
    COUNTY_BY_NAME.get(municipality.trim().toLowerCase()) ??
    COUNTY_BY_SLUG.get(slugify(municipality)) ??
    null
  );
}
