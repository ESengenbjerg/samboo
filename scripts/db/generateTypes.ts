// Writes shared/database.types.ts from the database (tables, functions, enums).
// Run from the repo root after every change to the database, right after dumping supabase/schema.sql:
//   npm run gen:types
// Needs the Supabase CLI and `supabase login` once (same as the dump in docs/database-design.md).
// Never edit shared/database.types.ts by hand: the next run overwrites it.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

process.loadEnvFile(".env");

const OUTPUT = "shared/database.types.ts";

// "https://abcdefgh.supabase.co" -> "abcdefgh"
const url = process.env.EXPO_PUBLIC_SUPABASE_URL ?? "";
const ref = url.match(/^https:\/\/([a-z0-9]+)\.supabase\.co/)?.[1];

if (!ref) {
  throw new Error("Could not read the project ref from EXPO_PUBLIC_SUPABASE_URL in .env");
}

// Only the public schema: auth, storage and the others belong to Supabase and are not used by our code
const types = execFileSync(
  "supabase",
  ["gen", "types", "typescript", `--remote=${ref}`, "--schema", "public"],
  { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] },
);

const header =
  "// GENERATED by `npm run gen:types` (scripts/db/generateTypes.ts). Do not edit by hand.\n\n";

writeFileSync(OUTPUT, header + types);
console.log(`Wrote ${OUTPUT} from project ${ref}`);
